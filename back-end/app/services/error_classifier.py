import asyncio

from app.config import get_settings
from app.core.errors import (
    AuthenticationRequiredError,
    BotVerificationRequiredError,
    DownloaderException,
    ExtractorOrVersionError,
    NetworkTimeoutError,
    POTokenConfigurationError,
    RateLimitedError,
    ServerConfigurationError,
    UnknownDownloadError,
    VideoUnavailableError,
)
from app.core.logging import logger


def classify_ytdlp_error(exc: Exception, url: str) -> DownloaderException:
    """
    Centralized, deterministic error classifier mapping yt-dlp exceptions,
    HTTP status codes, and extractor diagnostics to the canonical error taxonomy.
    Ensures zero sensitive credentials leak in error messages or details.
    """
    if isinstance(exc, DownloaderException):
        return exc

    if isinstance(exc, (TimeoutError, asyncio.TimeoutError)):
        return NetworkTimeoutError(
            message="Media analysis or download timed out. The upstream server was unresponsive.",
            user_action="The operation timed out. Please retry in a few moments.",
            details=str(exc),
        )

    err_str = str(exc)
    err_msg = err_str.lower()
    settings = get_settings()

    # 1. Proof-of-Origin (PO Token) Generation & Provider Failures
    if any(k in err_msg for k in (
        "potokenprovider", "get_pot", "pot-provider", "bgutil", "bgutil:http",
        "bgutil:script", "pot provider", "error reaching post /get_pot",
        "error reaching get",
    )) or ("po_token" in err_msg and any(f in err_msg for f in ("fail", "error", "refuse", "reject", "unreach", "connect", "timeout", "not available"))):
        logger.warning(f"[ErrorClassifier] PO Token generation failure: {exc}")
        return POTokenConfigurationError(
            message="YouTube requested a Proof-of-Origin (PO Token) that could not be generated by the provider.",
            user_action="Check the PO Token Provider service connectivity, logs, and configuration.",
            details=err_str,
        )

# 2. YouTube Bot Verification & BotGuard Challenges
    if any(k in err_msg for k in ("confirm you're not a bot", "confirm you\u2019re not a bot", "bot verification", "botguard", "automated queries", "captcha")):
        has_cookies = bool(settings.resolved_cookiefile)
        has_pot = bool(settings.resolved_po_token_provider_url or settings.YOUTUBE_PO_TOKEN)
        has_proxy = bool(settings.resolved_youtube_proxy)

        if has_cookies:
            msg = (
                "YouTube challenged this request with bot verification. "
                "The configured authentication cookies may have expired or need renewal."
            )
            action = "Update YOUTUBE_COOKIES with fresh cookies exported from an authorized session."
        elif has_pot and not has_proxy:
            # PO Token provider configured but no proxy - likely embedded provider on cloud IP
            msg = (
                "YouTube challenged this request with bot verification. "
                "The embedded PO Token provider runs on the same cloud IP and its tokens are rejected by YouTube's BotGuard."
            )
            action = (
                "REQUIRED for YouTube on cloud hosting (Render, etc.): Configure YOUTUBE_COOKIES (exported browser cookies) "
                "or YOUTUBE_PROXY_URL (residential proxy). The embedded PO Token provider cannot bypass BotGuard on cloud IPs. "
                "See: https://github.com/yt-dlp/yt-dlp/wiki/FAQ#how-do-i-pass-cookies-to-yt-dlp"
            )
        elif has_proxy:
            msg = (
                "YouTube challenged this request with bot verification. "
                "The configured proxy address may be restricted by YouTube."
            )
            action = "Verify that YOUTUBE_PROXY is an authorized, operational residential proxy."
        else:
            msg = (
                "YouTube temporarily challenged this request with bot verification on this server. "
                "To resolve on cloud hosts, configure YOUTUBE_COOKIES or a residential PROXY."
            )
            action = "Configure authorized YouTube cookies (YOUTUBE_COOKIES) or a residential proxy (YOUTUBE_PROXY_URL)."

        logger.warning(f"[ErrorClassifier] YouTube bot check triggered for {url}. Details: {exc}")
        return BotVerificationRequiredError(message=msg, user_action=action, details=err_str)

    # 3. Authentication & Account Access Required
    if any(k in err_msg for k in (
        "sign in", "login", "logged-in", "members only", "premium", "join this channel",
        "account required", "the web client only works when logged-in",
        "empty media response", "api is not granting access",
    )):
        platform_name = "This media"
        if "instagram" in err_msg or "instagram" in url.lower():
            platform_name = "Instagram"
        elif "vimeo" in err_msg or "vimeo" in url.lower():
            platform_name = "Vimeo"
        elif "tiktok" in err_msg or "tiktok" in url.lower():
            platform_name = "TikTok"
        elif "twitter" in err_msg or "x.com" in url.lower():
            platform_name = "X (Twitter)"
        elif "youtube" in err_msg or "youtube" in url.lower():
            platform_name = "YouTube"

        return AuthenticationRequiredError(
            message=f"{platform_name} requires a signed-in account or authorized cookies to access.",
            user_action="Configure authorized cookies with account access or check if the post is public.",
            details=err_str,
        )

    if any(k in err_msg for k in ("confirm your age", "sign in to confirm your age", "age-restricted", "age restricted", "age-gated", "age gate", "age verification")):
        return AuthenticationRequiredError(
            message="This content is age-restricted and requires account authentication.",
            user_action="Configure authorized cookies for an age-verified account.",
            details=err_str,
        )

    if "private" in err_msg or "account is private" in err_msg:
        platform_name = "This media"
        if "instagram" in url.lower():
            platform_name = "Instagram post"
        elif "twitter" in url.lower() or "x.com" in url.lower():
            platform_name = "X (Twitter) post"
        elif "youtube" in url.lower():
            platform_name = "YouTube video"

        return AuthenticationRequiredError(
            message=f"{platform_name} is private and cannot be accessed without account authorization.",
            user_action="Verify permissions or supply authorized cookies.",
            details=err_str,
        )

    # 4. Server Configuration (FFmpeg / system binary missing)
    if "ffmpeg" in err_msg and any(k in err_msg for k in ("not found", "missing", "no such file")):
        return ServerConfigurationError(
            message="Media processing failed because FFmpeg is not available on this server.",
            user_action="Ensure FFmpeg is installed and accessible on PATH.",
            details=err_str,
        )

    # 5. Media Not Found / Unavailable / Removed / Suspended
    if any(k in err_msg for k in (
        "not found", "404", "unavailable", "does not exist", "video has been removed",
        "deleted", "copyright", "suspended account", "this tweet is from a suspended account",
        "tweet has been deleted",
    )):
        return VideoUnavailableError(
            message="The requested media was not found or is no longer available.",
            user_action="Verify that the URL is correct, public, and not region-blocked.",
            details=err_str,
        )

    # 6. No Supported Formats / No Media In Post
    if any(k in err_msg for k in (
        "no video could be found", "no video formats found", "no media found", "no formats found"
    )):
        return ExtractorOrVersionError(
            message="No downloadable video or media stream was found for this link.",
            user_action="Verify that the post or tweet contains an attached video or media file.",
            details=err_str,
        )

    # 7. Host 403 Forbidden
    if any(k in err_msg for k in ("http error 403: forbidden", "403: forbidden")):
        return VideoUnavailableError(
            message="The host server rejected access to this media stream (HTTP 403 Forbidden).",
            user_action="The media may be expired, geo-restricted, or require direct browser access.",
            details=err_str,
        )

    # 8. Rate Limits & 429
    if any(k in err_msg for k in ("429", "too many requests", "rate limit")):
        return RateLimitedError(
            message="The media source or server has rate-limited requests.",
            user_action="Wait a few minutes before retrying your download.",
            details=err_str,
        )

    # 9. Network & Connection Timeouts
    if any(k in err_msg for k in ("timed out", "connection refused", "network is unreachable", "connection reset", "socket timeout", "temporary failure in name resolution")):
        return NetworkTimeoutError(
            message="A temporary network error occurred while connecting to the source.",
            user_action="Check your connection or wait a moment for the source to respond.",
            details=err_str,
        )

    # 10. Unsupported URL or Extractor/Parser issues
    if any(k in err_msg for k in ("unsupported url", "no suitable extractor")):
        return ExtractorOrVersionError(
            message="That URL is not currently supported.",
            user_action="Verify that the link is supported (e.g. YouTube, Instagram, TikTok, X, etc.).",
            details=err_str,
        )

    # 9. Generic Fallback
    logger.error(f"[ErrorClassifier] Unclassified download error: {exc}")
    return UnknownDownloadError(
        message=f"Extraction or download failed: {exc}",
        user_action="Please verify the URL or try downloading an alternative format.",
        details=err_str,
    )
