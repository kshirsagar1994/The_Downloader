#!/usr/bin/env python3
"""
YouTube Cookie Export Helper
============================
This script helps you export YouTube cookies from your browser for use with the downloader.

Usage:
    python scripts/export_youtube_cookies.py --browser chrome
    python scripts/export_youtube_cookies.py --browser firefox --output cookies.txt
    python scripts/export_youtube_cookies.py --browser edge --format base64

Requirements:
    pip install browser-cookie3

Supported browsers: chrome, firefox, edge, safari, brave, opera, vivaldi
"""

import argparse
import base64
import sys
from pathlib import Path

try:
    import browser_cookie3
except ImportError:
    print("❌ browser-cookie3 not installed. Install with: pip install browser-cookie3")
    sys.exit(1)


def export_cookies(browser: str, domain: str = "youtube.com") -> list:
    """Export cookies from specified browser for a domain."""
    browser_funcs = {
        "chrome": browser_cookie3.chrome,
        "firefox": browser_cookie3.firefox,
        "edge": browser_cookie3.edge,
        "safari": browser_cookie3.safari,
        "brave": browser_cookie3.brave,
        "opera": browser_cookie3.opera,
        "vivaldi": browser_cookie3.vivaldi,
    }

    if browser.lower() not in browser_funcs:
        raise ValueError(f"Unsupported browser: {browser}. Supported: {list(browser_funcs.keys())}")

    try:
        print(f"🔍 Extracting cookies from {browser.title()} for {domain}...")
        cookies = browser_funcs[browser.lower()](domain_name=domain)
        cookie_list = list(cookies)
        print(f"✅ Found {len(cookie_list)} cookies for {domain}")
        return cookie_list
    except Exception as e:
        print(f"❌ Failed to extract cookies from {browser}: {e}")
        print("   Make sure the browser is CLOSED and you're logged into YouTube.")
        return []


def format_netscape(cookies: list) -> str:
    """Format cookies as Netscape HTTP Cookie File format."""
    lines = [
        "# Netscape HTTP Cookie File",
        "# This file was generated by export_youtube_cookies.py",
        "# https://github.com/yt-dlp/yt-dlp/wiki/FAQ#how-do-i-pass-cookies-to-yt-dlp",
        "",
    ]

    for cookie in cookies:
        # Netscape format: domain, flag, path, secure, expiration, name, value
        domain = cookie.domain
        flag = "TRUE" if domain.startswith(".") else "FALSE"
        path = cookie.path or "/"
        secure = "TRUE" if cookie.secure else "FALSE"
        expires = str(int(cookie.expires)) if cookie.expires else "0"
        name = cookie.name
        value = cookie.value

        lines.append(f"{domain}\t{flag}\t{path}\t{secure}\t{expires}\t{name}\t{value}")

    return "\n".join(lines)


def format_json(cookies: list) -> str:
    """Format cookies as JSON array."""
    import json
    cookie_dicts = []
    for cookie in cookies:
        cookie_dicts.append({
            "domain": cookie.domain,
            "name": cookie.name,
            "value": cookie.value,
            "path": cookie.path,
            "secure": cookie.secure,
            "expires": cookie.expires,
            "httpOnly": getattr(cookie, "httponly", False),
        })
    return json.dumps(cookie_dicts, indent=2)


def main():
    parser = argparse.ArgumentParser(
        description="Export YouTube cookies from browser for use with yt-dlp",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s --browser chrome
  %(prog)s --browser firefox --output cookies.txt
  %(prog)s --browser edge --format base64
  %(prog)s --browser chrome --domain youtube.com --format netscape --output yt_cookies.txt

After getting cookies, set in Render Dashboard:
  Environment Variable: YOUTUBE_COOKIES
  Value: (paste the base64 output or Netscape format content)
        """
    )
    parser.add_argument("--browser", "-b", required=True,
                        choices=["chrome", "firefox", "edge", "safari", "brave", "opera", "vivaldi"],
                        help="Browser to extract cookies from")
    parser.add_argument("--domain", "-d", default="youtube.com",
                        help="Cookie domain (default: youtube.com)")
    parser.add_argument("--format", "-f", choices=["netscape", "json", "base64"], default="base64",
                        help="Output format (default: base64 for Render env var)")
    parser.add_argument("--output", "-o", help="Output file path (default: stdout)")

    args = parser.parse_args()

    cookies = export_cookies(args.browser, args.domain)

    if not cookies:
        print("⚠️  No cookies found. Make sure:")
        print("   1. You're logged into YouTube in that browser")
        print("   2. The browser is COMPLETELY CLOSED (not just the YouTube tab)")
        print("   3. You're not in incognito/private mode")
        sys.exit(1)

    # Filter for important YouTube cookies
    important_cookies = ["SID", "HSID", "SSID", "APISID", "SAPISID", "LOGIN_INFO", "VISITOR_INFO1_LIVE", "YSC"]
    filtered = [c for c in cookies if c.name in important_cookies or "youtube" in c.domain]

    if not filtered:
        filtered = cookies  # Use all if none of the important ones found

    print(f"📋 Using {len(filtered)} relevant cookies")

    if args.format == "netscape":
        output = format_netscape(filtered)
    elif args.format == "json":
        output = format_json(filtered)
    else:  # base64
        netscape = format_netscape(filtered)
        output = base64.b64encode(netscape.encode("utf-8")).decode("ascii")

    if args.output:
        Path(args.output).write_text(output, encoding="utf-8")
        print(f"💾 Saved to {args.output}")
    else:
        print("\n" + "=" * 60)
        print("COPY THE FOLLOWING FOR RENDER ENVIRONMENT VARIABLE:")
        print("=" * 60)
        print(output)
        print("=" * 60)

    print("\n📝 Next steps:")
    print("1. Go to your Render service dashboard")
    print("2. Add Environment Variable: YOUTUBE_COOKIES")
    print("3. Paste the base64 output above as the value")
    print("4. Redeploy the service")
    print("\n💡 Tip: Cookies expire! Re-export and update when YouTube stops working.")


if __name__ == "__main__":
    main()